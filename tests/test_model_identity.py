"""Routing identity follows each run instead of earlier assistant messages."""
import json
import sys
import tempfile
import time
import unittest
from pathlib import Path
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'server'))
import app


class ModelIdentityTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.rt = app.Runtime(root / 'data', root / 'work')
        for pid, name in [('old', 'ChatGPT'), ('router', 'OpenRouter')]:
            self.rt.store.put('providers', dict(id=pid, kind='openai', name=name,
                base_url='http://127.0.0.1', model='provider-default', has_key=False, tools_enabled=True))
        self.rt.store.put('sessions', dict(id='s', title='test', provider_id='old',
            model='gpt-old', mode='chat', created_at=app.now(), updated_at=app.now()))
        self.rt.message('s', 'user', 'Which model are you?')
        self.rt.message('s', 'assistant', 'I am GPT-5.')

    def tearDown(self):
        for event in list(self.rt.controls.values()): event.set()
        deadline = time.monotonic() + 5
        while self.rt.controls and time.monotonic() < deadline: time.sleep(.01)
        self.rt.store.db.close()
        self.tmp.cleanup()

    def run_and_wait(self, body):
        rid = self.rt.start('s', body)['run_id']
        deadline = time.monotonic() + 5
        while self.rt.store.get('runs', rid)['status'] in app.ACTIVE and time.monotonic() < deadline:
            time.sleep(.01)
        result = self.rt.store.get('runs', rid)
        self.assertEqual(result['status'], 'completed', result.get('error'))
        return result

    def test_new_model_overrides_earlier_identity_and_records_served_model(self):
        captured = []
        def complete(provider, context, *args, **kwargs):
            captured.append((provider, context))
            return {'content':'test reply','tool_calls':[], 'usage':{}, 'actual_model':'vendor/model-served'}
        with patch.object(app.providers, 'complete', side_effect=complete):
            run = self.run_and_wait({'content':'Are you Nemotron?', 'provider_id':'router',
                'model':'nvidia/nemotron:free', 'mode':'chat'})
        provider, context = captured[0]
        self.assertEqual(provider['model'], 'nvidia/nemotron:free')
        self.assertEqual(run['model'], 'nvidia/nemotron:free')
        self.assertEqual(run['actual_model'], 'vendor/model-served')
        self.assertIn('I am GPT-5.', [m['content'] for m in context])
        instruction = context[0]['content']
        self.assertIn(json.dumps({'provider':'OpenRouter','requested_model':'nvidia/nemotron:free'}, ensure_ascii=False), instruction)
        self.assertIn('Earlier assistant messages may have been generated by a different model', instruction)
        self.assertIn('not proof of the exact model served', instruction)
        self.assertNotIn('api_key', instruction)

    def test_server_default_and_missing_served_identity_are_not_invented(self):
        system = self.rt.system([], self.rt.settings(), {'name':'Account'}, '')
        self.assertIn('"requested_model": null', system)
        self.assertIn('provider default was selected', system)
        with patch.object(app.providers, 'complete', return_value={'content':'ok','tool_calls':[],'usage':{}}):
            run = self.run_and_wait({'content':'hello','provider_id':'router','model':'route-alias','mode':'chat'})
        self.assertEqual(run['model'], 'route-alias')
        self.assertIsNone(run['actual_model'])


if __name__ == '__main__': unittest.main()
